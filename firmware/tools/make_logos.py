"""Regenerates include/logos.h from the series' official logo files.

Downloads each logo, crops it, recolours where needed for a dark background,
fits it inside the menu button's logo box and pre-blends it onto the button
colour as RGB565 (LovyanGFX in this project has no alpha-blended image draw).

    pip install pillow pymupdf
    python tools/make_logos.py
"""
import io
import os
import urllib.request

import pymupdf
from PIL import Image

BOX_W, BOX_H = 210, 64          # logo area inside a menu button
BUTTON_BG = (0x1C, 0x1C, 0x25)  # C_ROW_B in src/ui.cpp

LOGOS = [
    ("LOGO_F1", "https://media.formula1.com/image/upload/v1677237319/etc/designs/fom-website/images/f1_logo.svg"),
    ("LOGO_FA", "https://www.f1academy.com/_next/static/images/fa_logo_footer-1992667600d4ff845995310220de58a8.png"),
    ("LOGO_PCC", "https://res.cloudinary.com/dmwcbhehi/image/upload/v1769454904/Porsche_Carrera_Cup_North_America_Logo_fcoh2b.png"),
]

OUT = os.path.join(os.path.dirname(__file__), "..", "include", "logos.h")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=30).read()


def load(name, url):
    data = fetch(url)
    if url.endswith(".svg"):
        page = pymupdf.open(stream=data, filetype="svg")[0]
        pix = page.get_pixmap(matrix=pymupdf.Matrix(8, 8), alpha=True)
        img = Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGBA")
    else:
        img = Image.open(io.BytesIO(data))

    if img.mode == "RGB":
        # Logo on a black background: brightness becomes opacity.
        px = img.load()
        out = Image.new("RGBA", img.size)
        opx = out.load()
        for y in range(img.height):
            for x in range(img.width):
                r, g, b = px[x, y]
                a = max(r, g, b)
                opx[x, y] = (0, 0, 0, 0) if a == 0 else (r * 255 // a, g * 255 // a, b * 255 // a, a)
        img = out
    img = img.convert("RGBA")

    if name == "LOGO_F1":
        # The published SVG is the white variant; use F1 red on the dark menu.
        r, g, b, a = img.split()
        red = Image.new("RGBA", img.size, (0xE1, 0x06, 0x00, 255))
        red.putalpha(a)
        img = red

    img = img.crop(img.getchannel("A").point(lambda v: 255 if v > 12 else 0).getbbox())
    scale = min(BOX_W / img.width, BOX_H / img.height)
    img = img.resize((max(1, round(img.width * scale)), max(1, round(img.height * scale))), Image.LANCZOS)

    bg = Image.new("RGBA", img.size, BUTTON_BG + (255,))
    bg.alpha_composite(img)
    return bg.convert("RGB")


def to_rgb565(img):
    raw = img.tobytes()
    return [((raw[i] & 0xF8) << 8) | ((raw[i + 1] & 0xFC) << 3) | (raw[i + 2] >> 3) for i in range(0, len(raw), 3)]


def main():
    parts = [
        "#pragma once",
        "// Generated by tools/make_logos.py -- do not edit.",
        "// Series logos are trademarks of their owners; for personal display only.",
        "#include <cstdint>",
        "",
        "struct Logo {",
        "  uint16_t w, h;",
        "  const uint16_t* rgb565;  // pre-blended onto the menu button colour",
        "};",
        "",
    ]
    names = []
    for name, url in LOGOS:
        img = load(name, url)
        px = to_rgb565(img)
        print(f"{name}: {img.width}x{img.height}")
        img.save(os.path.join(os.path.dirname(__file__), f"{name.lower()}_preview.png"))
        parts.append(f"static const uint16_t {name}_DATA[{len(px)}] = {{")
        for i in range(0, len(px), 16):
            parts.append("  " + ", ".join(f"0x{v:04X}" for v in px[i:i + 16]) + ",")
        parts.append("};")
        parts.append(f"static const Logo {name} = {{{img.width}, {img.height}, {name}_DATA}};")
        parts.append("")
        names.append(name)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
